# E0-09's supervision-edge trigger with the role-rank rule added. Read this
# against revision `014ccb3d0fe5`, which carries the long note on the five
# details of the original that are load-bearing — the schema qualification, the
# `AFTER` timing, the `CYCLE` clause, the walk over assignment ids rather than
# `person_id`, and the advisory lock. All five are unchanged. What is new is
# below, and there are three parts to it.
#
# **The rank is the position of a role in SPEC §2.1's canonical chain**, held as
# one array so that the order exists in exactly one place. `array_position`
# answers `NULL` for a role that is not in the chain — `CARE` and `ADMIN` — and
# every comparison below treats that as a refusal rather than as a zero. That is
# the same fail-closed shape `SCOPE_GRAIN_RULE`'s `ELSE false` gives the scope
# rule, and for the same reason: a role added to the enum without a rank cannot
# be given an edge at all until somebody decides where it sits.
#
# **An edge is legal only where `rank(child) < rank(parent)`**, which is the rule
# E0-09 left measured and unenforced. Its two named failures are an equal-rank
# edge — `LEAD_FACULTY -> LEAD_FACULTY`, which puts one lead's courses inside a
# sibling lead's purview and is SPEC §4.1 invariant 2 written as a row — and an
# inversion such as `VP_ACADEMICS -> CHAIR`, which puts the whole institution
# inside a chair's. Neither row is wrong on its face and neither errors.
#
# **The rank is read off the two assignments and never off the person holding
# them.** §2.1 attaches the edge to the assignment — "`reportsTo` edges connect
# role assignments, not people or org nodes" — and calls two-hat people ordinary:
# a lead who also teaches a section of somebody else's course holds an
# `INSTRUCTOR` assignment whose edge to that course's lead is legal. A rule
# written over `person_id` refuses that and passes every refusal test there is,
# which is the trap ADR 0027 already records for the cycle walk.
#
# **The rank check runs before the cycle walk, and that changes which rule
# answers for a cycle.** Every cycle contains at least one edge that does not
# increase in rank, so the rank rule refuses the closing edge of every cycle this
# schema can now express, and E0-09's cycle guard is reached only where the rank
# rule has already passed. Both are kept: the cycle walk is what still holds if a
# later ticket changes the rank order, adds a role, or replaces this rule, and
# `docs/MISTAKES.md` entry 3 is explicit that where two rules can refuse the same
# row, the behavioural test cannot say which one did. ADR 0044 carries the
# consequence in full, including the depth bound the rank order imposes.
#
# **The mirror of the edge rule, on the row at the top of the edge.** An edge can
# also be made illegal by changing the *parent's* role — an administrator editing
# a chair into a lead faculty member in §6.3's People editor leaves whatever
# reported to that chair reporting to a lead. E0-09's Care rule already closes the
# same shape for the same reason (a row that "may not become a CARE assignment
# while other assignments report to it"), and closing it for one rule and not the
# other is `docs/MISTAKES.md` entry 13 exactly. It runs only on an `UPDATE` that
# changes the role: no row can have children at the moment it is inserted, so an
# ordinary insert pays nothing for it, and the advisory lock is taken on that
# narrow condition rather than on every write.
#
# It sits after E0-09's Care rule so that a chair with children turned into a
# `CARE` assignment is still refused by the rule named for it, with the message
# that names it, rather than by the rank rule underneath.
SUPERVISION_EDGE_TRIGGER_FUNCTION = """
CREATE OR REPLACE FUNCTION public.role_assignment_refuse_illegal_supervision_edge() RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
    supervision_chain constant public.assignment_role[] := ARRAY[
        'INSTRUCTOR',
        'LEAD_FACULTY',
        'CHAIR',
        'ASSISTANT_DEAN',
        'DEAN',
        'VP_ACADEMICS'
    ]::public.assignment_role[];
    role_changed boolean;
    parent_role public.assignment_role;
    child_rank integer;
    parent_rank integer;
    closes_a_cycle boolean;
BEGIN
    role_changed := TG_OP = 'UPDATE' AND OLD.role IS DISTINCT FROM NEW.role;

    IF NEW.reports_to IS NOT NULL OR NEW.role = 'CARE' OR role_changed THEN
        IF current_setting('transaction_isolation') = 'repeatable read' THEN
            RAISE EXCEPTION
                'role assignment % carries a supervision edge, the CARE role or a changed role, '
                'and this transaction is REPEATABLE READ. The guards that refuse reporting '
                'cycles and illegal supervision edges read the rest of the graph, and at this '
                'isolation level that read uses a snapshot taken before any concurrent edge was '
                'committed, so a cycle written by two transactions at once would be stored. Use '
                'READ COMMITTED or SERIALIZABLE.',
                NEW.id
                USING ERRCODE = 'check_violation';
        END IF;
        PERFORM pg_advisory_xact_lock('public.role_assignment'::regclass::oid::bigint);
    END IF;

    IF NEW.reports_to IS NOT NULL THEN
        SELECT above.role INTO parent_role
          FROM public.role_assignment AS above
         WHERE above.id = NEW.reports_to;

        IF parent_role = 'CARE' THEN
            RAISE EXCEPTION
                'role assignment % may not report to %: a CARE assignment is never the '
                'target of a reporting edge, because it supervises nothing (SPEC 2.1)',
                NEW.id, NEW.reports_to
                USING ERRCODE = 'check_violation';
        END IF;

        child_rank := array_position(supervision_chain, NEW.role);
        parent_rank := array_position(supervision_chain, parent_role);

        IF child_rank IS NULL OR parent_rank IS NULL OR child_rank >= parent_rank THEN
            RAISE EXCEPTION
                'role assignment % in role % may not report to % in role %: a supervision edge '
                'runs from a role to one that outranks it in the chain INSTRUCTOR, LEAD_FACULTY, '
                'CHAIR, ASSISTANT_DEAN, DEAN, VP_ACADEMICS (SPEC 2.1), and a role outside that '
                'chain holds no rank to compare',
                NEW.id, NEW.role, NEW.reports_to, parent_role
                USING ERRCODE = 'check_violation';
        END IF;

        WITH RECURSIVE ancestor (assignment_id) AS (
                SELECT NEW.reports_to
            UNION ALL
                SELECT above.reports_to
                  FROM public.role_assignment AS above
                  JOIN ancestor ON above.id = ancestor.assignment_id
                 WHERE above.reports_to IS NOT NULL
        ) CYCLE assignment_id SET already_walked USING walked
        SELECT EXISTS (SELECT 1 FROM ancestor WHERE ancestor.assignment_id = NEW.id)
          INTO closes_a_cycle;

        IF closes_a_cycle THEN
            RAISE EXCEPTION
                'role assignment % may not report to %: the edge closes a reporting cycle '
                'in the supervision graph',
                NEW.id, NEW.reports_to
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;

    IF NEW.role = 'CARE' AND EXISTS (
        SELECT 1 FROM public.role_assignment AS below WHERE below.reports_to = NEW.id
    ) THEN
        RAISE EXCEPTION
            'role assignment % may not become a CARE assignment while other assignments '
            'report to it: a CARE assignment sits outside the supervision graph (SPEC 2.1)',
            NEW.id
            USING ERRCODE = 'check_violation';
    END IF;

    IF role_changed AND EXISTS (
        SELECT 1
          FROM public.role_assignment AS below
         WHERE below.reports_to = NEW.id
           AND (
                   array_position(supervision_chain, below.role) IS NULL
                OR array_position(supervision_chain, NEW.role) IS NULL
                OR array_position(supervision_chain, below.role)
                   >= array_position(supervision_chain, NEW.role)
           )
    ) THEN
        RAISE EXCEPTION
            'role assignment % may not change to role %: an assignment already reporting to it '
            'holds a role that the new one does not outrank in the chain INSTRUCTOR, '
            'LEAD_FACULTY, CHAIR, ASSISTANT_DEAN, DEAN, VP_ACADEMICS (SPEC 2.1). Re-point what '
            'reports to it first.',
            NEW.id, NEW.role
            USING ERRCODE = 'check_violation';
    END IF;

    RETURN NULL;
END;
$$
"""

